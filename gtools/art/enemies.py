"""Enemy sprites remastered in Atari 2600 / 80s arcade shmup aesthetic.

4bpp indexed format with 0 border touches on all frames to eliminate clipping.
Paint entries (palette 6-9) carry the chain/team color (Red, Blue, Yellow, Gray).
Metal (2-5), Glow (10-11), Canopy (12-13), Dark (14), White (15).
"""

import numpy as np


def _parse_frames(art_list, fw, fh):
    frames = []
    for rows in art_list:
        f = np.zeros((fh, fw), dtype=np.uint8)
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch != ".":
                    f[y, x] = int(ch, 16)
        frames.append(f)
    return frames


