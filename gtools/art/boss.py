"""Stage 1 boss, GAMMA CORE: a fortress-ship assembled from separate parts.

Each part is its own sprite with its own hit points, so it can be shot
off. Destroyed parts are redrawn with the BOSS_WRECK palette.

Remastered in authentic Atari 2600 / 80s arcade shmup aesthetic with 0 border touches
on all standalone sprite frames to prevent VERA Mode 5 scaling artifacts.
"""

import numpy as np

from kit import Material

MATS = {
    "armor": Material([2, 3, 4, 5, 6]),
    "plate": Material([2, 3, 4, 5]),
    "gold": Material([7, 8, 9]),
    "core": Material([10], shaded=False),
    "corehot": Material([11], shaded=False),
    "vent": Material([12, 13], dither=0.0),
    "light": Material([14], shaded=False),
    "lightb": Material([15], shaded=False),
}


def _parse_frames(art_list, fw, fh):
    frames = []
    for rows in art_list:
        f = np.zeros((fh, fw), dtype=np.uint8)
        assert len(rows) == fh, f"bad h: {len(rows)} != {fh}"
        for y, row in enumerate(rows):
            assert len(row) == fw, f"bad w at row {y}: {len(row)} != {fw}"
            for x, ch in enumerate(row):
                if ch != ".":
                    f[y, x] = int(ch, 16)
        frames.append(f)
    return frames


