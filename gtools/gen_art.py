#!/usr/bin/env python3
"""Generate every graphic in the game.

Writes, under images/:
  <sheet>.png           shared sprite sheets, frames side by side (indexed, 16 colors)
  logo.png              the title logo, 1 bit per pixel, in 64-pixel pieces
and for each level, under images/level<N>/ (packed into ROM:level<N>.bin
by tools/mklevel.py, and loaded into XRAM when the level starts):
  <enemy>.png           the level's enemy sprite sheets
  far_tiles.png         plane 0 tiles (8x8): sky, aurora, ridges
  mid_tiles.png         plane 1 tiles (8x8): hills, forest, lake
  fg_tiles.png          plane 2 tiles (16x16): the ground, compounds, home base
  far_map.bin, mid_map.bin, fg_map.bin   the tile maps, one byte per tile
  palettes.bin          every palette, RGB555 with the alpha bit
  level.json            what goes in the bank, and where
and src/gen/assets.h with the sizes, counts and world layout the game
needs. The build converts the PNGs (tools/png2bin.py), so the PNGs can be
touched up by hand in an editor like Aseprite.

Sprite sheets are hand-edited, so this leaves any that exist alone; pass
--sprites to redraw them all from the code, or --sprites NAME... for some.
The tile layers are always redrawn.

  .venv/bin/python gtools/gen_art.py [--preview DIR] [--sprites [NAME ...]]

--preview writes mock screenshots of each level and the sprites to DIR.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from chop import boreal, boreal_sprites, far, fg, logo, mid, pal, sprites, tilemap  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / "images"
GEN = ROOT / "src" / "gen"

# Tile budgets. Together with the sprites these fill XRAM; the game's
# xram.h asserts that the whole layout fits.
FAR_TILES = 214
MID_TILES = 224
FG_TILES = 192

# Level 1's enemies (tank, jet, balloon), out of sprites.py; the rest of
# sprites.py is shared by every level.
LEVEL1_ENEMIES = ("tank", "jet", "balloon")

LEVELS = [
    {"n": 1, "far": far.paint, "mid": mid.paint, "fg": fg.paint,
     "enemies": [s for s in sprites.SHEETS if s[0] in LEVEL1_ENEMIES]},
    {"n": 2, "far": boreal.far_paint, "mid": boreal.mid_paint, "fg": boreal.fg_paint,
     "enemies": boreal_sprites.SHEETS},
]
SHARED = [s for s in sprites.SHEETS if s[0] not in LEVEL1_ENEMIES]


def save_png(path, pixels, palette):
    img = Image.fromarray(np.asarray(pixels, np.uint8), "P")
    flat = [v for c in palette for v in c]
    img.putpalette(flat + [0] * (768 - len(flat)))
    img.save(path, transparency=0)


def preview(out: Path, level, layers, sheets):
    """Mock screens at a few camera positions, and a sprite contact sheet."""
    out.mkdir(parents=True, exist_ok=True)
    (ft, fmap), (mt, mmap), (gt, gmap) = layers
    f = tilemap.render(ft, fmap, 8)
    m = tilemap.render(mt, mmap, 8)
    g = tilemap.render(gt, gmap, 16)
    FP, MP, GP = (np.array(pal.level_pal(level, k)) for k in ("FAR", "MID", "FG"))
    X = np.arange(320)
    for cam in (fg.COMPOUND_COLS[0] * 16 - 60, 1600, fg.COMPOUND_COLS[3] * 16 - 40, 3776):
        img = np.zeros((240, 320, 3), np.uint8)
        for y in range(far.FAR_Y, far.FAR_Y + far.H):
            img[y] = FP[f[y - far.FAR_Y][(X + cam // 4) % far.W]]
        for y in range(mid.MID_Y, mid.MID_Y + mid.H):
            row = m[y - mid.MID_Y][(X + cam // 2) % mid.W]
            img[y][row != 0] = MP[row[row != 0]]
        for y in range(fg.FG_Y, fg.FG_Y + fg.H):
            row = g[y - fg.FG_Y][X + cam]
            img[y][row != 0] = GP[row[row != 0]]
        Image.fromarray(img).resize((960, 720), Image.NEAREST).save(out / f"screen_{cam}.png")
    rows = []
    bg = np.array([70, 80, 110])
    for name, w, h, frames, pn in sheets:
        pp = np.array(pal.level_pal(level, pn))
        row = np.zeros((h + 4, (w + 4) * len(frames), 3), np.uint8)
        row[:] = bg
        for i, fr in enumerate(frames):
            rgb = pp[fr]
            rgb[fr == 0] = bg
            row[2:2 + h, i * (w + 4) + 2:i * (w + 4) + 2 + w] = rgb
        rows.append(row)
    W = max(r.shape[1] for r in rows)
    img = np.vstack([np.pad(r, ((0, 0), (0, W - r.shape[1]), (0, 0))) for r in rows])
    Image.fromarray(img).resize((img.shape[1] * 4, img.shape[0] * 4), Image.NEAREST).save(out / "sprites.png")


def sheet_bytes(w, h, frames):
    return w * h // 2 * frames


def header(shared, levels, enemy_bytes, maps):
    """levels: one dict per level: n, enemies (name, w, h, frames, pal),
    offsets {name: offset in the enemy region}, door {intact, breached, row0}."""
    L = ["/* Generated by gtools/gen_art.py. Do not edit; regenerate instead. */",
         "#ifndef ASSETS_H", "#define ASSETS_H", "", "#include <stdint.h>", ""]
    L.append("/* Palettes, in XRAM order. Each level's bank brings its own set. */")
    for i, (name, _) in enumerate(pal.ORDER):
        L.append(f"#define PAL_{name} {i}")
    L.append(f"#define PAL_COUNT {len(pal.ORDER)}")
    L.append("/* Level 2's enemies use level 1's enemy slots. */")
    L.append("#define PAL_JEEP PAL_TANK")
    L.append("#define PAL_TURRET PAL_BALLOON")
    L.append("#define PAL_WORM PAL_JET")
    L.append(f"#define FAR_AURORA_FIRST {pal.FAR_AURORA} /* five entries the game rotates */")
    L.append(f"#define MID_BEACON_INDEX {pal.MID_BEACON}")
    L.append(f"#define AURORA_WAVE_N {len(pal.AURORA_WAVE)}")
    L.append("")
    L.append("/* The levels, each a bank in ROM: ROM:level<N>.bin. */")
    L.append(f"#define LEVEL_BANKS {len(levels)}")
    L.append("static const uint16_t aurora_waves[LEVEL_BANKS][AURORA_WAVE_N] = {")
    for lv in levels:
        L.append("    {" + ", ".join(f"0x{pal.rgb555(c):04X}" for c in pal.AURORA_WAVES[lv['n']]) + "},")
    L.append("};")
    L.append("static const uint16_t mid_beacon_on[LEVEL_BANKS] = {"
             + ", ".join(f"0x{pal.rgb555(pal.level_pal(lv['n'], 'MID')[pal.MID_BEACON]):04X}" for lv in levels) + "};")
    L.append(f"#define MID_BEACON_OFF 0x{pal.rgb555((70, 14, 18)):04X}")
    L.append("")
    L.append("/* Sprite sheets: frame size, frame count, bytes per frame (4bpp). */")
    for name, w, h, frames, _ in shared:
        N = name.upper()
        L += [f"#define {N}_W {w}", f"#define {N}_H {h}", f"#define {N}_FRAMES {len(frames)}",
              f"#define {N}_FRAME_BYTES {w * h // 2}"]
    L.append(f"#define LOGO_W {logo.W}")
    L.append(f"#define LOGO_H {logo.H}")
    L.append(f"#define LOGO_PIECE_W {logo.PIECE}")
    L.append(f"#define LOGO_PIECES {logo.W // logo.PIECE}")
    L.append(f"#define LOGO_PIECE_BYTES {logo.PIECE * logo.H // 8} /* 1 bit per pixel */")
    L.append("")
    L.append("/* Each level's enemies share one region of XRAM, filled from its bank:")
    L.append(" * <NAME>_OFS is where a sheet starts in it. */")
    L.append(f"#define ENEMY_IMG_BYTES {enemy_bytes}")
    for lv in levels:
        L.append(f"/* Level {lv['n']} */")
        for name, w, h, frames, _ in lv["enemies"]:
            N = name.upper()
            L += [f"#define {N}_W {w}", f"#define {N}_H {h}", f"#define {N}_FRAMES {len(frames)}",
                  f"#define {N}_FRAME_BYTES {w * h // 2}", f"#define {N}_OFS {lv['offsets'][name]}"]
    L.append("")
    L.append("/* Tile layers: room for this many tiles, whatever a level uses. */")
    budgets = {"far": FAR_TILES, "mid": MID_TILES, "fg": FG_TILES}
    for key, t, (rows, cols), y in (("FAR", 8, maps["far"], far.FAR_Y), ("MID", 8, maps["mid"], mid.MID_Y),
                                    ("FG", 16, maps["fg"], fg.FG_Y)):
        L += [f"#define {key}_TILE {t}", f"#define {key}_TILES {budgets[key.lower()]}",
              f"#define {key}_TILE_BYTES {t * t // 2}", f"#define {key}_MAP_COLS {cols}",
              f"#define {key}_MAP_ROWS {rows}", f"#define {key}_Y {y}"]
    L.append("")
    L.append("/* The world, the same in every level. */")
    L.append(f"#define WORLD_W_PX {fg.W}")
    L.append(f"#define GROUND_LINE {fg.GROUND_LINE} /* screen row of the ground's surface */")
    L.append(f"#define NUM_COMPOUNDS {len(fg.COMPOUND_COLS)}")
    L.append("static const uint8_t compound_cols[NUM_COMPOUNDS] = {" + ", ".join(map(str, fg.COMPOUND_COLS)) + "};")
    L.append(f"#define DOOR_COL {fg.DOOR_COL}")
    L.append(f"#define DOOR_W {fg.DOOR_W}")
    L.append(f"#define DOOR_H {fg.DOOR_H}")
    L.append(f"#define HOME_PAD_X0 {fg.PAD_COL0 * 16}")
    L.append(f"#define HOME_PAD_X1 {fg.PAD_COL1 * 16}")
    L.append(f"#define HOME_DOOR_X {fg.HANGAR_DOOR_X}")
    L.append(f"#define FLAG_X {fg.FLAG_COL * 16 + 5}")
    L.append(f"#define FLAG_Y {fg.GROUND_LINE - 90}")
    L.append(f"#define BORDER_X {fg.BORDER_X} /* the border flag; the enemy stays west of it */")
    L.append(f"#define BORDER_FLAG_X {fg.BORDER_X + 1}")
    L.append("")
    L.append("/* The door's tiles in each level (and the row above it, with the")
    L.append(" * warning lamp), top row first: as built, and blown open. */")
    door0 = levels[0]["door"]
    L.append(f"#define DOOR_TILE_ROWS {len(door0['intact'])}")
    L.append(f"#define DOOR_TILE_ROW0 {door0['row0']} /* fg map row of the top of that */")
    for k in ("intact", "breached"):
        L.append(f"static const uint8_t door_{k}[LEVEL_BANKS][DOOR_TILE_ROWS][DOOR_W] = {{")
        for lv in levels:
            L.append("    {" + ", ".join("{" + ", ".join(map(str, r)) + "}" for r in lv["door"][k]) + "},")
        L.append("};")
    L += ["", "#endif /* ASSETS_H */", ""]
    return "\n".join(L)


def build_layers(lv):
    """Paint and cut a level's three layers. Returns the tiles and maps,
    and the door's tile ids."""
    far_img = lv["far"]()
    ft, fmap, _ = tilemap.build(far_img, 8, pal.level_pal(lv["n"], "FAR"), FAR_TILES, transparent0=False)
    mid_img = lv["mid"]()
    mt, mmap, _ = tilemap.build(mid_img, 8, pal.level_pal(lv["n"], "MID"), MID_TILES)
    fg_img, door_img = lv["fg"]()
    # The door's ids, as painted and blown open. Both sets are protected,
    # so neither is merged into the other or anything else.
    col0 = fg.COMPOUND_COLS[0] + fg.DOOR_COL
    row0 = fg.SURF // 16 - fg.DOOR_H - 1
    door_now = fg_img[row0 * 16:fg.SURF, col0 * 16:(col0 + fg.DOOR_W) * 16]
    # The landmarks are kept exact too: a prison, the border checkpoint and
    # the home base. Any merging needed to fit the budget comes out of the
    # open ground, where it shows least.
    def cols(c0, c1):
        return fg_img[:, c0 * 16:c1 * 16]
    landmarks = [cols(fg.COMPOUND_COLS[0], fg.COMPOUND_COLS[0] + fg.COMPOUND_W),
                 cols(fg.BORDER_COL - 4, fg.BORDER_COL + 6),
                 cols(fg.HANGAR_COL - 1, fg.W // 16)]
    gt, gmap, look = tilemap.build(fg_img, 16, pal.level_pal(lv["n"], "FG"), FG_TILES,
                                   extra=[door_img, door_now] + landmarks)
    intact = [[int(gmap[row0 + r, col0 + c]) for c in range(fg.DOOR_W)] for r in range(fg.DOOR_H + 1)]
    breached = [[look(door_img[r * 16:(r + 1) * 16, c * 16:(c + 1) * 16]) for c in range(fg.DOOR_W)]
                for r in range(fg.DOOR_H + 1)]
    for col in fg.COMPOUND_COLS:
        got = [[int(gmap[row0 + r, col + fg.DOOR_COL + c]) for c in range(fg.DOOR_W)] for r in range(fg.DOOR_H + 1)]
        assert got == intact, "every compound must share the same door tiles"
    return ((ft, fmap), (mt, mmap), (gt, gmap)), {"intact": intact, "breached": breached, "row0": row0}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=Path)
    ap.add_argument("--sprites", nargs="*", help="redraw these sprite sheets (all, if none named)")
    args = ap.parse_args()
    IMAGES.mkdir(exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)

    def redraw(name):
        return args.sprites is not None and (not args.sprites or name in args.sprites)

    def sheets_of(specs, where, level):
        out = []
        for name, w, h, fn, pn in specs:
            frames = fn()
            for f in frames:
                assert f.shape == (h, w), (name, f.shape)
                assert f.max() < 16, name
            out.append((name, w, h, frames, pn))
            path = where / f"{name}.png"
            if redraw(name) or not path.exists():
                save_png(path, np.concatenate(frames, axis=1), pal.level_pal(level, pn))
        return out

    shared = sheets_of(SHARED, IMAGES, 1)

    # The logo, 1 bit per pixel.
    lp = logo.pieces()
    save_png(IMAGES / "logo.png", np.concatenate(lp, axis=1), [(0, 0, 0), (255, 255, 255)])

    levels = []
    for spec in LEVELS:
        n = spec["n"]
        where = IMAGES / f"level{n}"
        where.mkdir(exist_ok=True)
        enemies = sheets_of(spec["enemies"], where, n)
        layers, door = build_layers(spec)
        offsets, at = {}, 0
        for name, w, h, frames, _ in enemies:
            offsets[name] = at
            at += sheet_bytes(w, h, len(frames))
        ((ft, fmap), (mt, mmap), (gt, gmap)) = layers
        for name, tiles, t, key in (("far", ft, 8, "FAR"), ("mid", mt, 8, "MID"), ("fg", gt, 16, "FG")):
            save_png(where / f"{name}_tiles.png", tilemap.sheet(tiles, t), pal.level_pal(n, key))
        for name, m in (("far", fmap), ("mid", mmap), ("fg", gmap)):
            (where / f"{name}_map.bin").write_bytes(m.astype(np.uint8).tobytes())
        (where / "palettes.bin").write_bytes(pal.blob(n))
        levels.append({"n": n, "enemies": enemies, "offsets": offsets, "used": at, "door": door,
                       "layers": layers, "where": where,
                       "counts": {"far": len(ft), "mid": len(mt), "fg": len(gt)}})
        if args.preview:
            preview(args.preview / f"level{n}", n, layers, shared + enemies)

    enemy_bytes = max(lv["used"] for lv in levels)
    maps = {k: v.shape for k, v in zip(("far", "mid", "fg"), (m for _, m in levels[0]["layers"]))}

    # Each level's bank: the enemy sheets (padded to the region), the tiles
    # (each layer padded to its budget), the maps, then the palettes, in the
    # order xram.h lays them out. tools/mklevel.py packs it.
    for lv in levels:
        rel = lv["where"].relative_to(ROOT).as_posix()
        items = []
        for name, w, h, frames, _ in lv["enemies"]:
            items.append({"png": f"{rel}/{name}.png", "w": w, "h": h, "size": sheet_bytes(w, h, len(frames))})
        items.append({"pad": enemy_bytes - lv["used"]})
        for name, t, budget in (("far", 8, FAR_TILES), ("mid", 8, MID_TILES), ("fg", 16, FG_TILES)):
            items.append({"png": f"{rel}/{name}_tiles.png", "w": t, "h": t, "max": budget * t * t // 2,
                          "size": budget * t * t // 2})
        for name in ("far", "mid", "fg"):
            r, c = maps[name]
            items.append({"bin": f"{rel}/{name}_map.bin", "size": r * c})
        items.append({"bin": f"{rel}/palettes.bin", "size": len(pal.ORDER) * 32})
        (lv["where"] / "level.json").write_text(json.dumps({"items": items}, indent=1) + "\n")

    (GEN / "assets.h").write_text(header(shared, levels, enemy_bytes, maps))

    spr_bytes = sum(sheet_bytes(w, h, len(f)) for _, w, h, f, _ in shared)
    print(f"shared sprites {spr_bytes} B, enemy region {enemy_bytes} B")
    for lv in levels:
        c = lv["counts"]
        print(f"level {lv['n']}: enemies {lv['used']} B, tiles far {c['far']}/{FAR_TILES}, "
              f"mid {c['mid']}/{MID_TILES}, fg {c['fg']}/{FG_TILES}")


if __name__ == "__main__":
    main()
