#!/usr/bin/env python3
"""Generate every graphic in the game.

Writes, under images/:
  <sheet>.png           sprite sheets, frames side by side (indexed, 16 colors)
  logo.png              the title logo, 1 bit per pixel, in 64-pixel pieces
  far_tiles.png         plane 0 tiles (8x8): sky, aurora, mountains
  mid_tiles.png         plane 1 tiles (8x8): hills and forest
  fg_tiles.png          plane 2 tiles (16x16): the ground, compounds, home base
  far_map.bin, mid_map.bin, fg_map.bin   the tile maps, one byte per tile
  palettes.bin          every palette, RGB555 with the alpha bit
and src/gen/assets.h with the sizes, counts and world layout the game
needs. The build converts the PNGs (tools/png2bin.py), so the PNGs can be
touched up by hand in an editor like Aseprite; rerunning this overwrites
them.

  .venv/bin/python gtools/gen_art.py [--preview DIR]

--preview writes mock screenshots of the layers and sprites to DIR.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from chop import far, fg, logo, mid, pal, sprites, tilemap  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / "images"
GEN = ROOT / "src" / "gen"

# Tile budgets. Together with the sprites these fill XRAM; the game's
# xram.h asserts that the whole layout fits.
FAR_TILES = 224
MID_TILES = 224
FG_TILES = 192


def save_png(path, pixels, palette):
    img = Image.fromarray(np.asarray(pixels, np.uint8), "P")
    flat = [v for c in palette for v in c]
    img.putpalette(flat + [0] * (768 - len(flat)))
    img.save(path, transparency=0)


def preview(out: Path, layers, sheets):
    """Mock screens at a few camera positions, and a sprite contact sheet."""
    out.mkdir(parents=True, exist_ok=True)
    (ft, fmap), (mt, mmap), (gt, gmap) = layers
    f = tilemap.render(ft, fmap, 8)
    m = tilemap.render(mt, mmap, 8)
    g = tilemap.render(gt, gmap, 16)
    FP, MP, GP = map(np.array, (pal.FAR, pal.MID, pal.FG))
    X = np.arange(320)
    for cam in (fg.COMPOUND_COLS[0] * 16 - 60, 1600, fg.COMPOUND_COLS[3] * 16 - 40, 3776):
        img = np.zeros((240, 320, 3), np.uint8)
        for y in range(far.FAR_Y, far.FAR_Y + far.H):
            img[y] = FP[f[y - far.FAR_Y][(X + cam // 4) % far.W]]
        for y in range(mid.MID_Y, mid.MID_Y + mid.H):
            row = m[y - mid.MID_Y][(X + cam // 2) % mid.W]
            img[y][row != 0] = MP[row[row != 0]]
        for y in range(fg.FG_Y, fg.FG_Y + fg.H):
            row = g[y - fg.FG_Y][X + cam]
            img[y][row != 0] = GP[row[row != 0]]
        Image.fromarray(img).resize((960, 720), Image.NEAREST).save(out / f"screen_{cam}.png")
    rows = []
    pals = dict(pal.ORDER)
    bg = np.array([70, 80, 110])
    for name, w, h, frames, pn in sheets:
        pp = np.array(pals[pn])
        row = np.zeros((h + 4, (w + 4) * len(frames), 3), np.uint8)
        row[:] = bg
        for i, fr in enumerate(frames):
            rgb = pp[fr]
            rgb[fr == 0] = bg
            row[2:2 + h, i * (w + 4) + 2:i * (w + 4) + 2 + w] = rgb
        rows.append(row)
    W = max(r.shape[1] for r in rows)
    img = np.vstack([np.pad(r, ((0, 0), (0, W - r.shape[1]), (0, 0))) for r in rows])
    Image.fromarray(img).resize((img.shape[1] * 4, img.shape[0] * 4), Image.NEAREST).save(out / "sprites.png")


def header(sheets, counts, door, maps):
    L = ["/* Generated by gtools/gen_art.py. Do not edit; regenerate instead. */",
         "#ifndef ASSETS_H", "#define ASSETS_H", "", "#include <stdint.h>", ""]
    L.append("/* Palettes, in XRAM order. */")
    for i, (name, _) in enumerate(pal.ORDER):
        L.append(f"#define PAL_{name} {i}")
    L.append(f"#define PAL_COUNT {len(pal.ORDER)}")
    L.append(f"#define FAR_AURORA_FIRST {pal.FAR_AURORA} /* five entries the game rotates */")
    L.append(f"#define MID_BEACON_INDEX {pal.MID_BEACON}")
    L.append(f"#define FG_LAMP_INDEX {pal.FG_LAMP}")
    L.append(f"#define AURORA_WAVE_N {len(pal.AURORA_WAVE)}")
    L.append("static const uint16_t aurora_wave[AURORA_WAVE_N] = {")
    L.append("    " + ", ".join(f"0x{pal.rgb555(c):04X}" for c in pal.AURORA_WAVE) + ",")
    L.append("};")
    L.append(f"#define MID_BEACON_ON 0x{pal.rgb555(pal.MID[pal.MID_BEACON]):04X}")
    L.append(f"#define MID_BEACON_OFF 0x{pal.rgb555((70, 14, 18)):04X}")
    L.append(f"#define FG_LAMP_ON 0x{pal.rgb555(pal.FG[pal.FG_LAMP]):04X}")
    L.append(f"#define FG_LAMP_OFF 0x{pal.rgb555((150, 120, 60)):04X}")
    L.append("")
    L.append("/* Sprite sheets: frame size, frame count, bytes per frame (4bpp). */")
    for name, w, h, frames, _ in sheets:
        N = name.upper()
        L += [f"#define {N}_W {w}", f"#define {N}_H {h}", f"#define {N}_FRAMES {len(frames)}",
              f"#define {N}_FRAME_BYTES {w * h // 2}"]
    L.append(f"#define LOGO_W {logo.W}")
    L.append(f"#define LOGO_H {logo.H}")
    L.append(f"#define LOGO_PIECE_W {logo.PIECE}")
    L.append(f"#define LOGO_PIECES {logo.W // logo.PIECE}")
    L.append(f"#define LOGO_PIECE_BYTES {logo.PIECE * logo.H // 8} /* 1 bit per pixel */")
    L.append("")
    L.append("/* Tile layers. */")
    for key, t, (rows, cols), y, n in (("FAR", 8, maps["far"], far.FAR_Y, counts["far"]),
                                        ("MID", 8, maps["mid"], mid.MID_Y, counts["mid"]),
                                        ("FG", 16, maps["fg"], fg.FG_Y, counts["fg"])):
        L += [f"#define {key}_TILE {t}", f"#define {key}_TILES {n}", f"#define {key}_TILE_BYTES {t * t // 2}",
              f"#define {key}_MAP_COLS {cols}", f"#define {key}_MAP_ROWS {rows}", f"#define {key}_Y {y}"]
    L.append("")
    L.append("/* The world. */")
    L.append(f"#define WORLD_W_PX {fg.W}")
    L.append(f"#define GROUND_LINE {fg.GROUND_LINE} /* screen row of the snow's surface */")
    L.append(f"#define NUM_COMPOUNDS {len(fg.COMPOUND_COLS)}")
    L.append("static const uint8_t compound_cols[NUM_COMPOUNDS] = {" + ", ".join(map(str, fg.COMPOUND_COLS)) + "};")
    L.append(f"#define DOOR_COL {fg.DOOR_COL}")
    L.append(f"#define DOOR_W {fg.DOOR_W}")
    L.append(f"#define DOOR_H {fg.DOOR_H}")
    L.append(f"#define HOME_PAD_X0 {fg.PAD_COL0 * 16}")
    L.append(f"#define HOME_PAD_X1 {fg.PAD_COL1 * 16}")
    L.append(f"#define HOME_DOOR_X {fg.HANGAR_DOOR_X}")
    L.append(f"#define FLAG_X {fg.FLAG_COL * 16 + 5}")
    L.append(f"#define FLAG_Y {fg.GROUND_LINE - 90}")
    L.append(f"#define BORDER_X {fg.BORDER_X} /* the border flag; the enemy stays west of it */")
    L.append(f"#define BORDER_FLAG_X {fg.BORDER_X + 1}")
    L.append("")
    L.append("/* The door's tiles (and the row above it, with the warning lamp),")
    L.append(" * top row first: as built, and blown open. */")
    L.append(f"#define DOOR_TILE_ROWS {len(door['intact'])}")
    for k in ("intact", "breached"):
        L.append(f"static const uint8_t door_{k}[DOOR_TILE_ROWS][DOOR_W] = {{")
        for r in door[k]:
            L.append("    {" + ", ".join(map(str, r)) + "},")
        L.append("};")
    L.append(f"#define DOOR_TILE_ROW0 {door['row0']} /* fg map row of the top of that */")
    L += ["", "#endif /* ASSETS_H */", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=Path)
    args = ap.parse_args()
    IMAGES.mkdir(exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)

    sheets = []
    for name, w, h, fn, pn in sprites.SHEETS:
        frames = fn()
        for f in frames:
            assert f.shape == (h, w), (name, f.shape)
            assert f.max() < 16, name
        sheets.append((name, w, h, frames, pn))
        save_png(IMAGES / f"{name}.png", np.concatenate(frames, axis=1), dict(pal.ORDER)[pn])

    # The logo, 1 bit per pixel.
    lp = logo.pieces()
    save_png(IMAGES / "logo.png", np.concatenate(lp, axis=1), [(0, 0, 0), (255, 255, 255)])

    far_img = far.paint()
    ft, fmap, _ = tilemap.build(far_img, 8, pal.FAR, FAR_TILES, transparent0=False)
    mid_img = mid.paint()
    mt, mmap, _ = tilemap.build(mid_img, 8, pal.MID, MID_TILES)
    fg_img, door_img = fg.paint()
    # The door's ids, as painted and blown open. Both sets are protected,
    # so neither is merged into the other or anything else.
    col0 = fg.COMPOUND_COLS[0] + fg.DOOR_COL
    row0 = fg.SURF // 16 - fg.DOOR_H - 1
    door_now = fg_img[row0 * 16:fg.SURF, col0 * 16:(col0 + fg.DOOR_W) * 16]
    gt, gmap, look = tilemap.build(fg_img, 16, pal.FG, FG_TILES, extra=[door_img, door_now])
    intact = [[int(gmap[row0 + r, col0 + c]) for c in range(fg.DOOR_W)] for r in range(fg.DOOR_H + 1)]
    breached = [[look(door_img[r * 16:(r + 1) * 16, c * 16:(c + 1) * 16]) for c in range(fg.DOOR_W)]
                for r in range(fg.DOOR_H + 1)]
    for col in fg.COMPOUND_COLS:
        got = [[int(gmap[row0 + r, col + fg.DOOR_COL + c]) for c in range(fg.DOOR_W)] for r in range(fg.DOOR_H + 1)]
        assert got == intact, "every compound must share the same door tiles"

    for name, tiles, t, P in (("far", ft, 8, pal.FAR), ("mid", mt, 8, pal.MID), ("fg", gt, 16, pal.FG)):
        save_png(IMAGES / f"{name}_tiles.png", tilemap.sheet(tiles, t), P)
    for name, m in (("far", fmap), ("mid", mmap), ("fg", gmap)):
        (IMAGES / f"{name}_map.bin").write_bytes(m.astype(np.uint8).tobytes())
    (IMAGES / "palettes.bin").write_bytes(pal.blob())

    counts = {"far": len(ft), "mid": len(mt), "fg": len(gt)}
    maps = {"far": fmap.shape, "mid": mmap.shape, "fg": gmap.shape}
    (GEN / "assets.h").write_text(header(sheets, counts, {"intact": intact, "breached": breached, "row0": row0}, maps))

    spr_bytes = sum(w * h // 2 * len(f) for _, w, h, f, _ in sheets)
    tile_bytes = counts["far"] * 32 + counts["mid"] * 32 + counts["fg"] * 128
    map_bytes = sum(r * c for r, c in maps.values())
    print(f"sprites {spr_bytes} B, tiles {tile_bytes} B (far {counts['far']}, mid {counts['mid']}, fg {counts['fg']}), "
          f"maps {map_bytes} B, total {spr_bytes + tile_bytes + map_bytes} B")
    if args.preview:
        preview(args.preview, ((ft, fmap), (mt, mmap), (gt, gmap)), sheets)


if __name__ == "__main__":
    main()
