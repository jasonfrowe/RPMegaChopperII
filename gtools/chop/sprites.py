def flags():
    """A 24x16 maple-leaf flag on the pole, rippling; the pole is at its left."""
    frames = []
    leaf = grid("""
....r....
..r.rr.r.
.rrrrrrr.
rrrrrrrrr
.rrrrrrr.
..rrrrr..
....r....
....r....
""", {"r": 3})
    for f in range(4):
        out = np.zeros((16, 24), np.uint8)
        for x in range(23):
            off = int(round(1.4 * math.sin(x / 3.2 - f * math.pi / 2) * min(1, x / 6)))
            for y in range(1, 15):
                yy = y + off
                if not 0 <= yy < 16:
                    continue
                if y in (1, 14) or x == 22:
                    c = 1
                elif x < 6 or x > 16:
                    c = 3
                else:
                    c = 6
                out[yy, x] = c
        # The leaf, drawn into the white field and shaded by the ripple.
        for ly in range(8):
            for lx in range(9):
                if leaf[ly, lx]:
                    x = 7 + lx
                    off = int(round(1.4 * math.sin(x / 3.2 - f * math.pi / 2) * min(1, x / 6)))
                    out[4 + ly + off, x] = 3
        # Ripple shading.
        for x in range(23):
            sh = math.cos(x / 3.2 - f * math.pi / 2)
            col = out[:, x]
            if sh < -0.4:
                col[col == 3] = 2
                col[col == 6] = 5
            elif sh > 0.6:
                col[col == 3] = 4
        frames.append(out)
    return frames


