def _add_main_rotor(base, y, x_hub, blade, span_l=15, span_r=15, tilt=0.0):
    out = base.copy()
    for dx in range(-span_l, span_r + 1):
        x = x_hub + dx
        ry = int(round(y + dx * tilt))
        if not (0 <= x < CHOPPER_W and 0 <= ry < CHOPPER_H):
            continue
        adx = abs(dx)
        if adx <= 1:
            out[ry, x] = CK["o"] if adx == 1 else CK["m"]
        elif (dx < 0 and blade == 0) or (dx > 0 and blade == 1):
            if adx >= span_l - 1:
                out[ry, x] = CK["b"]
            elif adx % 3 == 0:
                out[ry, x] = CK["m"]
            else:
                out[ry, x] = CK["k"]
            if 0 <= ry + 1 < CHOPPER_H and out[ry + 1, x] == 0 and adx < 5:
                out[ry + 1, x] = CK["o"]
        elif adx <= 6:
            out[ry, x] = CK["b"] if adx <= 4 else CK["m"]
    return out


def _add_tail_rotor(out, cx, cy, blade):
    out[cy, cx] = CK["o"]
    if blade == 0:
        for d in (-2, -1, 1, 2):
            if 0 <= cy - d < CHOPPER_H and 0 <= cx + d < CHOPPER_W:
                out[cy - d, cx + d] = CK["b"] if abs(d) == 2 else CK["k"]
    else:
        for d in (-2, -1, 1, 2):
            if 0 <= cy + d < CHOPPER_H and 0 <= cx + d < CHOPPER_W:
                out[cy + d, cx + d] = CK["b"] if abs(d) == 2 else CK["k"]
        out[out == CK["y"]] = CK["P"]
    return out


def chopper():
    """Frames, in pairs (two rotor phases):
    0 side, 2 side nose down, 4 side nose up, 6 three-quarter, 8 front,
    10 front banking."""
    specs = [
        ("side", 1, 17, 15, 15, 0.0, (35, 5)),
        ("down", 2, 17, 15, 14, -0.12, (36, 3)),
        ("up", 1, 16, 14, 15, 0.12, (35, 8)),
        ("quarter", 2, 17, 15, 15, 0.0, (29, 7)),
        ("front", 2, 19, 15, 15, 0.0, None),
        ("bank", 2, 18, 15, 15, -0.11, None),
    ]
    frames = []
    for kind, ry, x_hub, sl, sr, tilt, tail in specs:
        base = grid(CHOPPER_BODIES[kind], CK)
        for blade in (0, 1):
            f = _add_main_rotor(base, ry, x_hub, blade, sl, sr, tilt)
            if tail is not None:
                f = _add_tail_rotor(f, tail[0], tail[1], blade)
            frames.append(f)
    return frames


